// Turns the SVGs exported from the Figma "wridge Icons" frame into web/app-icons.js for the window.
// Icon strokes become currentColor (the theme colours them); the wridge mark takes the theme's ink and accent.
// Run after exporting again: node web/icons/build.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const out = {};
for (const f of readdirSync(HERE).filter((x) => x.endsWith(".svg")).sort()) {
  let s = readFileSync(join(HERE, f), "utf8")
    .replace(/\s(width|height)="[^"]*"/, "")
    .replace(/\s(width|height)="[^"]*"/, "")
    .replace(/\sid="[^"]*"/g, "")
    .replace(/\n/g, "")
    .replace(/<svg /, '<svg aria-hidden="true" ');
  if (f.startsWith("icon-")) s = s.replace(/stroke="#3A3833"/g, 'stroke="currentColor"');
  if (f === "logo-wridge.svg") s = s.replace(/fill="#111111"/g, 'fill="currentColor"').replace(/fill="#2F6BFF"/g, 'style="fill:var(--primary)"').replace(/fill="#FBFAF8"/g, 'style="fill:var(--surface-1)"');
  out[f.replace(/\.svg$/, "").replace(/^icon-/, "")] = s;
}
writeFileSync(join(HERE, "..", "app-icons.js"), `// Generated by web/icons/build.mjs from the Figma "wridge Icons" frame — do not edit by hand.\nwindow.ICON = ${JSON.stringify(out, null, 1)};\n`);
console.log("icons:", Object.keys(out).join(" "));
